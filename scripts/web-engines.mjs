#!/usr/bin/env node
// What the on-device engines take from the web app, regenerated from a web checkout:
// 1. engine/src/main/resources/engine/transpile.js: the web's own transpile()
//    (src/lib/run/transpile.ts, sucrase) bundled for QuickJS, so JS/TS syntax
//    errors and output match the web exactly.
// 2. engine/src/test/resources/web/ruff.json: the web's Ruff version and settings,
//    and what its WASM Ruff (ruffFixAll) makes of sample code; the app's Ruff
//    binary must give the same (RuffTest).
// 3. core/src/test/resources/web/graph.json: the web's map edges and d3-force
//    layout for a sample graph (GraphTest compares the Kotlin port to it).
// 4. core/src/test/resources/web/math.json: which math remark-math (with remark-gfm,
//    as the web's markdown.tsx) finds in sample note bodies (MathTextTest).
// Package versions come from the web's package-lock.json. CI reruns this and fails on a diff.
//   node scripts/web-engines.mjs <path-to-web-checkout>
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ESBUILD = "0.24.2";
const web = resolve(process.argv[2] ?? "../research-notebook");
const root = resolve(import.meta.dirname, "..");
const tools = join(root, "build/js-tools");
const lock = JSON.parse(readFileSync(join(web, "package-lock.json"), "utf8"));
const version = (name) => {
  const v = lock.packages[`node_modules/${name}`]?.version;
  if (!v) throw new Error(`${name} not found in the web's package-lock.json`);
  return v;
};
const sucrase = version("sucrase");
const ruffWasm = version("@astral-sh/ruff-wasm-web");
const d3force = version("d3-force");
const mdPkgs = ["unified", "remark-parse", "remark-gfm", "remark-math", "unist-util-visit"].map((p) => [p, version(p)]);

mkdirSync(tools, { recursive: true });
const have = (name, version) => {
  const p = join(tools, "node_modules", name, "package.json");
  return existsSync(p) && JSON.parse(readFileSync(p, "utf8")).version === version;
};
if (!have("sucrase", sucrase) || !have("esbuild", ESBUILD) || !have("@astral-sh/ruff-wasm-web", ruffWasm) || !have("d3-force", d3force) || mdPkgs.some(([p, v]) => !have(p, v))) {
  writeFileSync(join(tools, "package.json"), JSON.stringify({ private: true }));
  const pkgs = [`sucrase@${sucrase}`, `esbuild@${ESBUILD}`, `@astral-sh/ruff-wasm-web@${ruffWasm}`, `d3-force@${d3force}`, ...mdPkgs.map(([p, v]) => `${p}@${v}`)];
  execFileSync("npm", ["install", "--no-save", "--no-package-lock", "--silent", ...pkgs], { cwd: tools, stdio: "inherit" });
}

const entry = join(tools, "entry.ts");
writeFileSync(
  entry,
  `import { transpile } from ${JSON.stringify(join(web, "src/lib/run/transpile.ts"))};\n` +
    `(globalThis as any).bjTranspile = (code: string, language: "javascript" | "typescript") => JSON.stringify(transpile(code, language));\n`,
);
const esbuild = await import(join(tools, "node_modules/esbuild/lib/main.js"));
const out = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "neutral",
  mainFields: ["module", "main"],
  target: "es2020",
  minify: true,
  legalComments: "none",
  nodePaths: [join(tools, "node_modules")],
  write: false,
  logLevel: "warning",
});
const dest = join(root, "engine/src/main/resources/engine/transpile.js");
writeFileSync(dest, `// Generated by scripts/build-transpiler.mjs from the web's src/lib/run/transpile.ts with sucrase ${sucrase}. Do not edit.\n` + out.outputFiles[0].text);
console.log(`wrote ${dest} (${out.outputFiles[0].text.length} bytes, sucrase ${sucrase})`);

// ---- Ruff: the web's settings (ruff.ts SETTINGS) and its WASM's fixes on samples
const ruffTs = readFileSync(join(web, "src/lib/run/ruff.ts"), "utf8");
const settingsSrc = /const SETTINGS = (\{[\s\S]*?\n\});/.exec(ruffTs)?.[1];
if (!settingsSrc) throw new Error("SETTINGS not found in src/lib/run/ruff.ts");
const SETTINGS = Function(`return (${settingsSrc.replace(/\/\/.*$/gm, "")});`)();
const ruff = await import(join(tools, "node_modules/@astral-sh/ruff-wasm-web/ruff_wasm.js"));
await ruff.default({ module_or_path: readFileSync(join(tools, "node_modules/@astral-sh/ruff-wasm-web/ruff_wasm_bg.wasm")) });
const ws = new ruff.Workspace(SETTINGS, ruff.PositionEncoding.Utf16);
const { applyEdits } = await import(pathToFileURL(join(web, "src/lib/run/ruff-fix.ts")).href);
// The web's ruffFixAll loop (ruff.ts), with its own applyEdits.
const fixAll = (code) => {
  let text = code;
  for (let pass = 0; pass < 5; pass++) {
    const edits = ws.check(text).flatMap((d) => d.fix?.edits ?? []);
    if (!edits.length) break;
    const next = applyEdits(text, edits);
    if (next === text) break;
    text = next;
  }
  return text;
};
const samples = [
  "import os\nimport sys\nprint(1)\n",
  'x = f"a"\nprint(x)\n',
  "def f():\n    y = 2\n    return 1\n",
  's = "🌍"; import json\nprint(s)\n',
  "import os, sys\nprint(sys.argv)\n",
  "print(1)\n",
  "def f(:\n",
  "from math import *\nimport re\nprint(pi)\n",
  "try:\n    pass\nexcept:\n    pass\nl = lambda: 0\n",
];
const ruffFixture = {
  version: ruffWasm,
  settings: SETTINGS,
  samples: samples.map((code) => ({ code, fixable: ws.check(code).filter((d) => d.fix?.edits.length).length, fixed: fixAll(code) })),
};
const fixtureDir = join(root, "engine/src/test/resources/web");
mkdirSync(fixtureDir, { recursive: true });
writeFileSync(join(fixtureDir, "ruff.json"), JSON.stringify(ruffFixture, null, 2) + "\n");
console.log(`wrote ${join(fixtureDir, "ruff.json")} (ruff ${ruffWasm})`);

// ---- Map: the web's buildEdges + layoutGraph on a sample graph
const graphJs = join(tools, "graph.mjs");
await esbuild.build({
  entryPoints: [join(web, "src/lib/graph.ts")], bundle: true, format: "esm", platform: "node",
  nodePaths: [join(tools, "node_modules")], outfile: graphJs, logLevel: "warning",
});
const { buildEdges, layoutGraph } = await import(pathToFileURL(graphJs).href);
const nid = (i) => `00000000-0000-4000-8000-${String(i).padStart(12, "0")}`;
const gNodes = Array.from({ length: 12 }, (_, i) => ({ id: nid(i), title: i === 6 ? "" : `Note ${i}`, parent_id: i > 0 && i % 4 === 0 ? nid(i - 4) : null }));
const gLinks = [
  { source: nid(1), label: "Note 2", id: null }, { source: nid(2), label: "x", id: nid(3) }, { source: nid(3), label: "note 1", id: null },
  { source: nid(5), label: "x", id: nid(9) }, { source: nid(9), label: "Note 5", id: null }, { source: nid(7), label: "x", id: nid(7) },
  { source: nid(4), label: "Note 0", id: null }, { source: nid(10), label: "Missing", id: null },
];
const gEdges = buildEdges(gNodes, gLinks);
const placed = layoutGraph(gNodes, gEdges);
writeFileSync(
  join(root, "core/src/test/resources/web/graph.json"),
  JSON.stringify({ nodes: gNodes, links: gLinks, edges: gEdges, placed: placed.map((p) => ({ id: p.id, x: +p.x.toFixed(3), y: +p.y.toFixed(3) })) }, null, 1) + "\n",
);
console.log("wrote core/src/test/resources/web/graph.json");

// ---- Math: what remark-math parses out of sample bodies
const mod = (p) => import(pathToFileURL(join(tools, "node_modules", p, "index.js")).href);
const { unified } = await mod("unified");
const remarkParse = (await mod("remark-parse")).default;
const remarkGfm = (await mod("remark-gfm")).default;
const remarkMath = (await mod("remark-math")).default;
const { visit } = await mod("unist-util-visit");
const parser = unified().use(remarkParse).use(remarkGfm).use(remarkMath);
const mathSamples = [
  "Energy $E = mc^2$ here.",
  "$$\n\\int_0^1 x\\,dx\n$$",
  "Price is $5 and $10 total.",
  "Escaped \\$5 and $x$.",
  "`$not math$` but $y$",
  "```\n$inside code$\n```\n\nafter $z$",
  "Two $$a+b$$ dollars inline",
  "Multi $a\nb$ line",
  "Space $ x $ trimmed",
  "Para one $a$\n\nPara two $b$",
  "- item $i$\n- other",
  "$$\nunclosed",
  "No math at all",
  "$$ x $$",
  "Text\n$$\ny\n$$\nmore $w$",
];
const found = mathSamples.map((md) => {
  const pieces = [];
  visit(parser.parse(md), (n) => {
    if (n.type === "inlineMath" || n.type === "math") pieces.push({ tex: n.value, display: n.type === "math" });
  });
  return { md, pieces };
});
writeFileSync(join(root, "core/src/test/resources/web/math.json"), JSON.stringify(found, null, 1) + "\n");
console.log("wrote core/src/test/resources/web/math.json");
